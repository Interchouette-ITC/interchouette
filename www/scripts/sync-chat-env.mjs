#!/usr/bin/env node
/**
 * Sync CHAT_WIDGET_ENABLED from `.env` / process.env into
 * `src/app/core/chat-widget.enabled.ts` (default: true).
 *
 * Usage: runs via npm prestart / prebuild / pretest.
 * Local: set CHAT_WIDGET_ENABLED=false in `.env`, then restart `npm start`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const wwwRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(wwwRoot, '..');
const outPath = join(wwwRoot, 'src/app/core/chat-widget.enabled.ts');

function parseDotEnv(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }
  const out = {};
  for (const line of readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const eq = trimmed.indexOf('=');
    if (eq <= 0) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

function parseEnabled(raw) {
  if (raw === undefined || raw === null || String(raw).trim() === '') {
    return true;
  }
  const v = String(raw).trim().toLowerCase();
  if (['0', 'false', 'off', 'no'].includes(v)) {
    return false;
  }
  if (['1', 'true', 'on', 'yes'].includes(v)) {
    return true;
  }
  return true;
}

const fileEnv = {
  ...parseDotEnv(join(repoRoot, '.env')),
  ...parseDotEnv(join(wwwRoot, '.env')),
};
const raw =
  process.env.CHAT_WIDGET_ENABLED !== undefined
    ? process.env.CHAT_WIDGET_ENABLED
    : fileEnv.CHAT_WIDGET_ENABLED;
const enabled = parseEnabled(raw);

const contents = `/** Generated by scripts/sync-chat-env.mjs - do not edit by hand. */
export const CHAT_WIDGET_ENABLED = ${enabled ? 'true' : 'false'};
`;

writeFileSync(outPath, contents);
const source =
  process.env.CHAT_WIDGET_ENABLED !== undefined
    ? 'process.env'
    : fileEnv.CHAT_WIDGET_ENABLED !== undefined
      ? '.env'
      : 'default';
console.log(`chat-widget.enabled.ts: CHAT_WIDGET_ENABLED=${enabled} (from ${source})`);
